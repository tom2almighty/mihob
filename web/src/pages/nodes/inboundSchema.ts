import type { TFunction } from "i18next"
import { z } from "zod"

export function createInboundSchema(t: TFunction) {
  return z.object({
    name: z.string().trim().min(1, t("nodes.inbound.validation.nameRequired")),
    tag: z.string().trim().optional(),
    tags: z.array(z.string()).optional(),
    proxy_name: z.string().trim().optional(),
    client_server: z.string().trim().optional(),
    client_port: z.coerce.number().int().min(0).max(65535).optional(),
    client_tls: z.boolean().optional(),
    client_endpoint_apis: z
      .array(
        z.object({
          url: z.string().trim(),
          name: z.string().trim().optional(),
          count: z.coerce.number().int().min(0).max(50).optional(),
          port: z.coerce.number().int().min(0).max(65535).optional(),
          enabled: z.boolean(),
        })
      )
      .optional(),
    protocol: z.enum([
      "vless",
      "vmess",
      "trojan",
      "hysteria2",
      "tuic",
      "anytls",
      "shadowsocks",
      "mieru",
      "trusttunnel",
      "shadowquic",
      "snell",
      "sudoku",
      "http",
      "socks",
      "mixed",
    ]),
    port: z.coerce
      .number()
      .int()
      .min(1, t("nodes.inbound.validation.portRange"))
      .max(65535, t("nodes.inbound.validation.portRange")),
    listen: z.string().trim(),
    cert_id: z.string().optional(),
    enabled: z.boolean(),
    security: z.enum(["none", "tls", "reality"]),
    sni: z.string().trim().optional(),
    alpn: z.string().trim().optional(),
    skip_cert_verify: z.boolean(),
    client_fingerprint: z.string().trim().optional(),
    ech_key: z.string().optional(),
    ech_enable: z.boolean().optional(),
    ech_config: z.string().trim().optional(),
    client_auth_type: z.string().trim().optional(),
    client_auth_cert: z.string().trim().optional(),
    port_range: z.string().trim().optional(),
    routing_mark: z.coerce.number().int().min(0).optional(),
    listener_rule: z.string().trim().optional(),
    listener_proxy: z.string().trim().optional(),
    network: z.enum(["tcp", "ws", "grpc", "xhttp"]),
    ws_path: z.string().trim().optional(),
    ws_host: z.string().trim().optional(),
    grpc_service_name: z.string().trim().optional(),
    xhttp_path: z.string().trim().optional(),
    xhttp_mode: z.string().trim().optional(),
    xhttp_host: z.string().trim().optional(),
    xhttp_no_sse_header: z.boolean().optional(),
    xhttp_x_padding_bytes: z.string().trim().optional(),
    flow: z.string().trim().optional(),
    vless_decryption: z.string().trim().optional(),
    vless_encryption: z.string().trim().optional(),
    alter_id: z.coerce.number().int().min(0).optional(),
    cipher: z.string().trim().optional(),
    reality_dest: z.string().trim().optional(),
    reality_server_names: z.string().trim().optional(),
    reality_private_key: z.string().trim().optional(),
    reality_public_key: z.string().trim().optional(),
    reality_short_ids: z.string().trim().optional(),
    up_mbps: z.coerce.number().int().min(0).optional(),
    down_mbps: z.coerce.number().int().min(0).optional(),
    ignore_client_bandwidth: z.boolean().optional(),
    obfs: z.string().trim().optional(),
    obfs_password: z.string().trim().optional(),
    masquerade: z.string().trim().optional(),
    hop_ports: z.string().trim().optional(),
    bbr_profile: z.string().trim().optional(),
    congestion_controller: z.string().trim().optional(),
    cwnd: z.coerce.number().int().min(0).optional(),
    max_idle_time: z.coerce.number().int().min(0).optional(),
    udp_relay_mode: z.string().trim().optional(),
    padding_scheme: z.string().optional(),
    ss_cipher: z.string().trim().optional(),
    ss_server_password: z.string().trim().optional(),
    mieru_transport: z.string().trim().optional(),
    mieru_port_range: z.string().trim().optional(),
    mieru_multiplexing: z.string().trim().optional(),
    mieru_handshake_mode: z.string().trim().optional(),
    mieru_traffic_pattern: z.string().trim().optional(),
    mieru_tcp_idle_timeout: z.coerce.number().int().min(0).optional(),
    mieru_user_hint_mandatory: z.boolean().optional(),
    trusttunnel_network: z.string().trim().optional(),
    trusttunnel_max_connections: z.coerce.number().int().min(0).optional(),
    trusttunnel_min_streams: z.coerce.number().int().min(0).optional(),
    trusttunnel_max_streams: z.coerce.number().int().min(0).optional(),
    name_cert_verify: z.string().trim().optional(),
    shadowquic_jls_addr: z.string().trim().optional(),
    shadowquic_jls_sni: z.string().trim().optional(),
    shadowquic_jls_proxy: z.string().trim().optional(),
    shadowquic_zero_rtt: z.boolean().optional(),
    snell_psk: z.string().trim().optional(),
    snell_version: z.coerce.number().int().min(1).max(6).optional(),
    snell_mode: z.string().trim().optional(),
    snell_obfs_mode: z.string().trim().optional(),
    snell_obfs_host: z.string().trim().optional(),
    sudoku_key: z.string().trim().optional(),
    sudoku_aead_method: z.string().trim().optional(),
    sudoku_table_type: z.string().trim().optional(),
    sudoku_custom_table: z.string().trim().optional(),
    sudoku_multiplex: z.string().trim().optional(),
    sudoku_disable_http_mask: z.boolean().optional(),
    sudoku_http_mask_mode: z.string().trim().optional(),
    sudoku_http_mask_tls: z.boolean().optional(),
    sudoku_http_mask_host: z.string().trim().optional(),
    sudoku_path_root: z.string().trim().optional(),
    sudoku_fallback: z.string().trim().optional(),
    sudoku_enable_pure_downlink: z.boolean().optional(),
    extra_server_yaml: z.string().optional(),
    extra_client_yaml: z.string().optional(),
  })
}

export type InboundFormValues = z.infer<ReturnType<typeof createInboundSchema>>
